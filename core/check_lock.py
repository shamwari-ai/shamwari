"""
Guards `requirements.txt` against drifting from `requirements.in`.

A lockfile does not fail loudly when it goes stale. It keeps installing an
old, valid, reproducible set that no longer matches what the spec asks for —
so someone adds a dependency, forgets to recompile, and the import error
shows up on the deploy rather than in the pull request.

Deliberately offline and deterministic. It does NOT re-resolve against PyPI:
a check that re-resolves goes red because a dependency published a release,
which turns an unrelated pull request into a false alarm and teaches everyone
to ignore the job. This asks only the question whose answer cannot change on
its own: does the lock pin every package the spec names, with hashes?
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
SPEC = HERE / "requirements.in"
LOCK = HERE / "requirements.txt"

# "uvicorn[standard]>=0.32" -> "uvicorn"; also handles ==, ~=, bare names.
_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def normalise(name: str) -> str:
    """PEP 503: underscores, hyphens and dots are equivalent."""
    return re.sub(r"[-_.]+", "-", name).lower()


def spec_names(text: str) -> set[str]:
    out: set[str] = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        m = _NAME.match(line)
        if m:
            out.add(normalise(m.group(1)))
    return out


def lock_pins(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#") or "==" not in stripped:
            continue
        m = _NAME.match(stripped)
        if not m:
            continue
        version = stripped.split("==", 1)[1].split()[0].strip("\\ ")
        out[normalise(m.group(1))] = version
    return out


PAIRS = [
    (HERE / "requirements.in", HERE / "requirements.txt"),
    (HERE / "requirements-ingest.in", HERE / "requirements-ingest.txt"),
]

#: Core holds no database login (the owner's rule: only the Nyuchi API talks to databases),
#: so its image must not carry a driver. The ingest lock may.
DATABASE_DRIVERS = {"motor", "pymongo", "asyncpg", "psycopg", "psycopg2", "dnspython"}


def check_pair(spec_path: Path, lock_path: Path) -> tuple[list[str], int]:
    problems: list[str] = []
    for p in (spec_path, lock_path):
        if not p.exists():
            return [f"missing {p.name}"], 0

    spec_text = spec_path.read_text()
    lock_text = lock_path.read_text()

    # 1. The lock must say it came from the spec. Catches a hand-written
    #    requirements.txt masquerading as generated.
    if spec_path.name not in lock_text:
        problems.append(
            f"{lock_path.name} does not reference {spec_path.name}; it may have been hand-edited "
            f"rather than generated by pip-compile"
        )

    # 2. Every package the spec names must be pinned in the lock.
    pins = lock_pins(lock_text)
    for name in sorted(spec_names(spec_text)):
        if name not in pins:
            problems.append(f"{name} is in {spec_path.name} but not pinned in {lock_path.name}: recompile")

    # 3. Hashes must be present, or --require-hashes silently buys nothing.
    if "--hash=sha256:" not in lock_text:
        problems.append(f"{lock_path.name} has no hashes; recompile with --generate-hashes")

    # 4. Nothing may be left unpinned.
    for line in lock_text.splitlines():
        s = line.split("#", 1)[0].strip()
        if not s or s.startswith(("-", "\\")) or s.startswith("--hash"):
            continue
        if _NAME.match(s) and "==" not in s:
            problems.append(f"{lock_path.name} has an unpinned requirement: {s!r}")

    # 5. The service lock carries no database driver.
    if lock_path.name == "requirements.txt":
        for name in sorted(DATABASE_DRIVERS & set(pins)):
            problems.append(f"{lock_path.name} pins {name}: Core's image must hold no database driver")

    return problems, len(pins)


def main() -> int:
    problems: list[str] = []
    counts: list[str] = []
    for spec, lock in PAIRS:
        found, n = check_pair(spec, lock)
        problems += found
        counts.append(f"{lock.name}: {n}")

    if problems:
        print("check_lock: FAIL", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1

    print(f"check_lock: ok, pinned with hashes ({'; '.join(counts)}), specs fully covered")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
