// Runs after `astro build`: writes the chat service worker (with a precache
// list of the exact hashed files this build produced) and the response headers
// for /chat/. Usage: node scripts/post-build.mjs [outDir]   (default dist)
//
// Both depend on the build output, which is why they are generated here
// instead of living in public/: the service worker's cache name changes only
// when a precached file does, and the CSP's connect-src names the API origin
// this build was pointed at (PUBLIC_SHAMWARI_API).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const out = process.argv[2] ?? 'dist';
const read = (p) => readFileSync(join(out, p));
const html = read('chat/index.html').toString('utf8');

const refs = [...html.matchAll(/(?:href|src)="(\/[^"#?]+)"/g)].map((m) => m[1]);
const precache = [...new Set(['/chat/', '/chat/manifest.webmanifest', ...refs.filter((r) => /^\/(_astro|chat)\//.test(r) || r === '/favicon.png' || r === '/apple-touch-icon.png'), '/chat/icons/icon-192.png'])].sort();

const version = createHash('sha256')
  .update(precache.map((p) => `${p}:${createHash('sha256').update(read(p.endsWith('/') ? `${p}index.html` : p)).digest('hex')}`).join('\n'))
  .digest('hex')
  .slice(0, 12);

const sw = `// Generated by scripts/post-build.mjs. Do not edit.
const CACHE = 'shamwari-chat-${version}';
const PRECACHE = ${JSON.stringify(precache)};
const SCOPE = '/chat/';

self.addEventListener('install', (e) => {
  // Precache is all-or-nothing: a half-cached shell is worse than none.
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('shamwari-chat-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Only same-origin GETs under /chat/ and its hashed assets are ever answered
// from here. The API is another origin and a POST, so a question and its answer
// never enter a cache.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (!url.pathname.startsWith(SCOPE) && !url.pathname.startsWith('/_astro/')) return;
  if (url.pathname === '/chat/sw.js') return;

  if (req.mode === 'navigate') {
    // Shell from cache, at once. It is NOT refreshed from here: fresh HTML would
    // name hashed assets that this worker's precache does not hold. A new build
    // ships a new worker (its file changes), which precaches the new shell and
    // assets together and then takes over.
    e.respondWith(caches.match('/chat/').then((hit) => hit || fetch(req)));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(out, 'chat/sw.js'), sw);

const api = new URL(process.env.PUBLIC_SHAMWARI_API ?? 'https://api.shamwari.ai').origin;
const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self'",
  `connect-src 'self' ${api}`,
  "manifest-src 'self'",
  "worker-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');
writeFileSync(
  join(out, '_headers'),
  `/chat/*
  Content-Security-Policy: ${csp}
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff

/chat/sw.js
  Cache-Control: no-cache

/chat/
  Cache-Control: no-cache

/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`,
);
console.log(`post-build: sw ${version} precaching ${precache.length} files; CSP connect-src ${api}`);
