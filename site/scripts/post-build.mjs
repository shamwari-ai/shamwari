// Runs after `astro build`: writes the chat service worker (with a precache
// list of the exact hashed files this build produced) and the response headers
// for /lite/. Usage: node scripts/post-build.mjs [outDir]   (default dist-app)
// It is the build step of the APP Worker only (npm run build:app); the marketing
// site has no service worker and no chat.
//
// Both depend on the build output, which is why they are generated here
// instead of living in public/: the service worker's cache name changes only
// when a precached file does, and the CSP's connect-src names the API origin
// this build was pointed at (PUBLIC_SHAMWARI_API).
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { authModeProblem } from '../check-auth-mode.mjs';

const out = process.argv[2] ?? 'dist-app';

// The release version people see ("v0.0.74"), never a commit. staging-version.yml tags every merge to staging
// as v0.0.N, so the latest release tag reachable from this build is its version. APP_VERSION overrides it (a
// deploy from a clone without tags says it); with neither, the package's own version, so the name is never blank.
function releaseVersion() {
  const given = process.env.APP_VERSION?.trim();
  if (given && /^v\d+\.\d+\.\d+$/.test(given)) return given;
  try {
    const tag = execFileSync('git', ['describe', '--tags', '--abbrev=0', '--match', 'v[0-9]*.[0-9]*.[0-9]*'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (/^v\d+\.\d+\.\d+$/.test(tag)) return tag;
  } catch {
    /* no git, or no tags in this clone */
  }
  return `v${JSON.parse(readFileSync(fileURLToPath(new URL('../package.json', import.meta.url)), 'utf8')).version}`;
}
const release = releaseVersion();

// The two icons the marketing site and the app share live once, in public/; the app
// build takes its copy here rather than keeping a second binary that can drift.
for (const icon of ['favicon.ico', 'favicon.png', 'apple-touch-icon.png']) copyFileSync(fileURLToPath(new URL(`../public/${icon}`, import.meta.url)), join(out, icon));
const read = (p) => readFileSync(join(out, p));
const html = read('lite/index.html').toString('utf8');

// The sign-in mode is checked HERE, in the build itself, so every way of building the app (npm run build:app, the Workers Build,
// deploy:app) refuses a page in the wrong mode, not only CI's `node check.mjs app`. Mukoko sign-in is the default; the developer-key
// screen is built only by PUBLIC_CHAT_AUTH=developer-key (chat/auth-mode.ts).
const modeProblem = authModeProblem(html);
if (modeProblem) throw new Error(`post-build: ${modeProblem}`);

const refs = [...html.matchAll(/(?:href|src)="(\/[^"#?]+)"/g)].map((m) => m[1]);

// Everything the shell can need offline: the files the page names, the files its
// scripts import, and the files its stylesheets point at. Reading the built files
// (not guessing) means a later shared chunk or a font in the CSS cannot be left
// out of the precache and break the shell offline.
const wanted = new Set(refs.filter((r) => /^\/lite\/_astro\//.test(r) || r === '/favicon.ico' || r === '/favicon.png' || r === '/apple-touch-icon.png'));
const queue = [...wanted];
while (queue.length) {
  const f = queue.pop();
  if (!/\.(js|css)$/.test(f)) continue;
  const code = read(f).toString('utf8');
  const found = f.endsWith('.js')
    ? [...code.matchAll(/(?:from|import)\s*\(?\s*["']\.\/([^"']+)["']/g)].map((m) => `/lite/_astro/${m[1]}`)
    : [...code.matchAll(/url\(\s*["']?(\/[^"')?#]+)/g)].map((m) => m[1]);
  for (const g of found) if (!wanted.has(g)) { wanted.add(g); queue.push(g); }
}
const precache = [...new Set(['/lite/', '/lite/disclaimer/', '/lite/manifest.webmanifest', ...wanted, '/lite/icons/icon-192.png'])].sort();

const version = createHash('sha256')
  .update(precache.map((p) => `${p}:${createHash('sha256').update(read(p.endsWith('/') ? `${p}index.html` : p)).digest('hex')}`).join('\n'))
  .digest('hex')
  .slice(0, 12);

const sw = `// Generated by scripts/post-build.mjs. Do not edit.
const VERSION = '${release}';
const CACHE = 'shamwari-chat-${version}';
const PRECACHE = ${JSON.stringify(precache)};
const SCOPE = '/lite/';

self.addEventListener('install', (e) => {
  // Precache is all-or-nothing: a half-cached shell is worse than none. Updates are FORCED: once the whole new shell is
  // cached this worker takes over at once (skipWaiting) instead of waiting for every tab to close, and the page reloads
  // itself once, when nothing is being sent or written (chat/update-reload.ts).
  e.waitUntil(
    // cache: 'reload' goes to the network, so a new build never precaches a stale copy from the browser's HTTP cache.
    caches.open(CACHE).then((c) => Promise.all(PRECACHE.map((u) => c.add(new Request(u, { cache: 'reload' }))))).then(() => self.skipWaiting()),
  );
});

// The page asks this worker for its version (shown at the foot of the drawer).
self.addEventListener('message', (e) => {
  if (e.data === 'version') e.ports[0]?.postMessage(VERSION);
});

self.addEventListener('activate', (e) => {
  // Drop every older cache and take every open page now, so no tab keeps running (or fetching) the old release.
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('shamwari-chat-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Only same-origin GETs under /lite/ (its hashed assets are there too) are ever answered
// from here. The API is another origin and a POST, so a question and its answer
// never enter a cache.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  // Sign-in is a server round trip: the login redirect, the OAuth callback and the token/logout calls must always
  // reach the network. They are at the ROOT (/auth/*, /callback), outside this worker's scope, so the scope check below would
  // leave them alone anyway; this explicit test comes first so it stays true if the scope ever widens, and the old
  // /lite/ addresses (kept for a release) are listed for the same reason. Serving the cached shell for a navigation to them would make
  // signing in impossible.
  if (url.pathname.startsWith('/auth/') || url.pathname === '/callback' || url.pathname.startsWith('/lite/auth/') || url.pathname === '/lite/callback') return;
  if (!url.pathname.startsWith(SCOPE)) return;
  if (url.pathname === '/lite/sw.js') return;

  if (req.mode === 'navigate') {
    // Shell from cache, at once. It is NOT refreshed from here: fresh HTML would
    // name hashed assets that this worker's precache does not hold. A new build
    // ships a new worker (its file changes), which precaches the new shell and
    // assets together and takes over once the old tabs are closed.
    // A page the worker precached (the disclaimer) is served as itself; any other address gets the shell.
    const page = PRECACHE.includes(url.pathname) && url.pathname.endsWith('/') ? url.pathname : '/lite/';
    e.respondWith(caches.match(page).then((hit) => hit || fetch(req)));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)));
});
`;
writeFileSync(join(out, 'lite/sw.js'), sw);

// The API origin comes from the built page itself, the one the app will really
// call, so the CSP and the app can never disagree (an env var and a .env file
// could, and a blocked request looks like "offline" to the person).
const metaApi = html.match(/<meta name="shamwari-api" content="([^"]+)"/)?.[1];
if (!metaApi) throw new Error('post-build: the chat page has no shamwari-api meta tag');
const api = new URL(metaApi).origin;
const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self'",
  // A voice note the person recorded is played from a blob: URL made on this device; nothing else may load media.
  "media-src 'self' blob:",
  `connect-src 'self' ${api}`,
  "manifest-src 'self'",
  "worker-src 'self'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ');
writeFileSync(
  join(out, '_headers'),
  `/lite/*
  Content-Security-Policy: ${csp}
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff

/lite/sw.js
  Cache-Control: no-cache

/lite/
  Cache-Control: no-cache

/lite/_astro/*
  Cache-Control: public, max-age=31536000, immutable
`,
);
console.log(`post-build: sw ${version} precaching ${precache.length} files; CSP connect-src ${api}`);
